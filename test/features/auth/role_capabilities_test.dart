import 'package:flutter_test/flutter_test.dart';
import 'package:flutter_application_1/features/auth/domain/models/role_capabilities.dart';
import 'package:flutter_application_1/features/auth/domain/models/user_role.dart';

void main() {
  group('RoleCapabilities Matrix Tests', () {
    test('Super Admin capabilities', () {
      expect(
        RoleCapabilities.hasCapability(
          UserRole.superAdmin,
          UserCapability.viewPlatformDashboard,
        ),
        isTrue,
      );
      expect(
        RoleCapabilities.hasCapability(
          UserRole.superAdmin,
          UserCapability.viewFirms,
        ),
        isTrue,
      );
      expect(
        RoleCapabilities.hasCapability(
          UserRole.superAdmin,
          UserCapability.manageFirms,
        ),
        isTrue,
      );
      // Super Admin does not manage firm-level operational data
      expect(
        RoleCapabilities.hasCapability(
          UserRole.superAdmin,
          UserCapability.createCase,
        ),
        isFalse,
      );
      expect(
        RoleCapabilities.hasCapability(
          UserRole.superAdmin,
          UserCapability.viewPayments,
        ),
        isFalse,
      );
    });

    test('Firm Admin capabilities', () {
      // Core Legal
      expect(
        RoleCapabilities.hasCapability(
          UserRole.firmAdmin,
          UserCapability.viewCases,
        ),
        isTrue,
      );
      expect(
        RoleCapabilities.hasCapability(
          UserRole.firmAdmin,
          UserCapability.createCase,
        ),
        isTrue,
      );
      expect(
        RoleCapabilities.hasCapability(
          UserRole.firmAdmin,
          UserCapability.editCase,
        ),
        isTrue,
      );
      expect(
        RoleCapabilities.hasCapability(
          UserRole.firmAdmin,
          UserCapability.deleteCase,
        ),
        isTrue,
      );

      // Operations
      expect(
        RoleCapabilities.hasCapability(
          UserRole.firmAdmin,
          UserCapability.viewTasks,
        ),
        isTrue,
      );
      expect(
        RoleCapabilities.hasCapability(
          UserRole.firmAdmin,
          UserCapability.createTask,
        ),
        isTrue,
      );
      expect(
        RoleCapabilities.hasCapability(
          UserRole.firmAdmin,
          UserCapability.viewDocuments,
        ),
        isTrue,
      );
      expect(
        RoleCapabilities.hasCapability(
          UserRole.firmAdmin,
          UserCapability.uploadDocuments,
        ),
        isTrue,
      );
      expect(
        RoleCapabilities.hasCapability(
          UserRole.firmAdmin,
          UserCapability.viewPayments,
        ),
        isTrue,
      );
      expect(
        RoleCapabilities.hasCapability(
          UserRole.firmAdmin,
          UserCapability.createPayments,
        ),
        isTrue,
      );

      // Administration
      expect(
        RoleCapabilities.hasCapability(
          UserRole.firmAdmin,
          UserCapability.viewTeam,
        ),
        isTrue,
      );
      expect(
        RoleCapabilities.hasCapability(
          UserRole.firmAdmin,
          UserCapability.manageTeam,
        ),
        isTrue,
      );
      expect(
        RoleCapabilities.hasCapability(
          UserRole.firmAdmin,
          UserCapability.viewSubscriptions,
        ),
        isTrue,
      );
      expect(
        RoleCapabilities.hasCapability(
          UserRole.firmAdmin,
          UserCapability.viewBranding,
        ),
        isTrue,
      );

      // Platform admin forbidden
      expect(
        RoleCapabilities.hasCapability(
          UserRole.firmAdmin,
          UserCapability.manageFirms,
        ),
        isFalse,
      );
    });

    test('Lawyer capabilities', () {
      // Core Legal
      expect(
        RoleCapabilities.hasCapability(
          UserRole.lawyer,
          UserCapability.viewCases,
        ),
        isTrue,
      );
      expect(
        RoleCapabilities.hasCapability(
          UserRole.lawyer,
          UserCapability.createCase,
        ),
        isTrue,
      );
      expect(
        RoleCapabilities.hasCapability(
          UserRole.lawyer,
          UserCapability.viewClients,
        ),
        isTrue,
      );
      expect(
        RoleCapabilities.hasCapability(
          UserRole.lawyer,
          UserCapability.viewHearings,
        ),
        isTrue,
      );

      // Operations
      expect(
        RoleCapabilities.hasCapability(
          UserRole.lawyer,
          UserCapability.viewTasks,
        ),
        isTrue,
      );
      expect(
        RoleCapabilities.hasCapability(
          UserRole.lawyer,
          UserCapability.createTask,
        ),
        isTrue,
      );
      expect(
        RoleCapabilities.hasCapability(
          UserRole.lawyer,
          UserCapability.viewDocuments,
        ),
        isTrue,
      );
      expect(
        RoleCapabilities.hasCapability(
          UserRole.lawyer,
          UserCapability.uploadDocuments,
        ),
        isTrue,
      );

      // Payments & Firm admin forbidden (Lawyer gets 403 on /api/payments/)
      expect(
        RoleCapabilities.hasCapability(
          UserRole.lawyer,
          UserCapability.viewPayments,
        ),
        isFalse,
      );
      expect(
        RoleCapabilities.hasCapability(
          UserRole.lawyer,
          UserCapability.createPayments,
        ),
        isFalse,
      );
      expect(
        RoleCapabilities.hasCapability(
          UserRole.lawyer,
          UserCapability.manageTeam,
        ),
        isFalse,
      );
      expect(
        RoleCapabilities.hasCapability(
          UserRole.lawyer,
          UserCapability.manageFirms,
        ),
        isFalse,
      );
    });

    test('Staff capabilities', () {
      // Core Legal (Clients and Hearings allowed, Cases forbidden with 403)
      expect(
        RoleCapabilities.hasCapability(
          UserRole.staff,
          UserCapability.viewClients,
        ),
        isTrue,
      );
      expect(
        RoleCapabilities.hasCapability(
          UserRole.staff,
          UserCapability.createClient,
        ),
        isTrue,
      );
      expect(
        RoleCapabilities.hasCapability(
          UserRole.staff,
          UserCapability.viewHearings,
        ),
        isTrue,
      );
      expect(
        RoleCapabilities.hasCapability(
          UserRole.staff,
          UserCapability.viewCases,
        ),
        isFalse,
      );
      expect(
        RoleCapabilities.hasCapability(
          UserRole.staff,
          UserCapability.createCase,
        ),
        isFalse,
      );

      // Operations (Tasks allowed, Documents and Payments forbidden with 403)
      expect(
        RoleCapabilities.hasCapability(
          UserRole.staff,
          UserCapability.viewTasks,
        ),
        isTrue,
      );
      expect(
        RoleCapabilities.hasCapability(
          UserRole.staff,
          UserCapability.createTask,
        ),
        isTrue,
      );
      expect(
        RoleCapabilities.hasCapability(
          UserRole.staff,
          UserCapability.viewDocuments,
        ),
        isFalse,
      );
      expect(
        RoleCapabilities.hasCapability(
          UserRole.staff,
          UserCapability.uploadDocuments,
        ),
        isFalse,
      );
      expect(
        RoleCapabilities.hasCapability(
          UserRole.staff,
          UserCapability.viewPayments,
        ),
        isFalse,
      );
      expect(
        RoleCapabilities.hasCapability(
          UserRole.staff,
          UserCapability.createPayments,
        ),
        isFalse,
      );

      // Administration forbidden
      expect(
        RoleCapabilities.hasCapability(
          UserRole.staff,
          UserCapability.manageTeam,
        ),
        isFalse,
      );
      expect(
        RoleCapabilities.hasCapability(
          UserRole.staff,
          UserCapability.manageFirms,
        ),
        isFalse,
      );
    });
  });
}
